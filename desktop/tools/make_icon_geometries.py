"""Writes src/LiteTunnel.App/Styles/Icons.axaml from the Android vector icons.

Material Symbols Rounded (Apache License 2.0), 960 x 960 viewport, the same
set the Android app uses. Run from desktop/: python3 -I tools/make_icon_geometries.py
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent.parent
source = here.parent / "android" / "app" / "src" / "main" / "res" / "drawable"
names = ["add", "arrow_back", "arrow_down", "arrow_up", "bolt", "bolt_fill", "campaign",
         "check_circle", "delete", "dns", "expand_more", "info", "more", "notes", "power",
         "refresh", "settings", "unchecked"]
lines = [
    "<!-- Generated by tools/make_icon_geometries.py from Material Symbols Rounded (Apache License 2.0). -->",
    '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
]
for name in names:
    text = (source / f"ic_{name}.xml").read_text(encoding="utf-8")
    if 'viewportHeight="960"' not in text:
        sys.exit(f"{name}: not a 960 viewport")
    paths = re.findall(r'android:pathData="([^"]+)"', text)
    if len(paths) != 1:
        sys.exit(f"{name}: {len(paths)} paths")
    lines.append(f'  <StreamGeometry x:Key="Icon.{name}">{paths[0]}</StreamGeometry>')
lines.append("</ResourceDictionary>")
out = here / "src" / "LiteTunnel.App" / "Styles" / "Icons.axaml"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(out.name, len(names))
